#!/bin/bash
# Regenerates golden_frames.inc from the engines' own Java encoders. Run after a wire schema
# bump (money v7, order v12) with jars built from the commits dependencies.lock pins:
#   adapters/sbe/tests/golden/regen.sh <assets-cluster.jar> <match-cluster.jar> [<assets-feed-harness.jar> [<e1-dir>]]
#
# RC2 S9h 4.1 (S9a 9.4): with the third argument, the S9h harness jar (pinned by feed_harness_sha256 in
# dependencies.lock) also writes the ONLY expected bytes the C++ translator is compared with:
#   - adapters/sbe/tests/golden/feed_frames.inc: every named case of S9h 4.2 (`fixtures` on the six committed
#     ME journal fixtures), NAME_IN = the case's FJR1 file bytes, NAME_OUT = its FFR1 file bytes, plus the
#     FEED_FRAME_CASES table; the header names the harness commit and jar sha256 and pins every case by hash;
#   - domain/bridge/tests/fixtures/e1/: the `e1` output (per scenario and member .fjr, .ffr, .refused.txt, e1.pin,
#     SHA256SUMS) for the E1 corpus; the corpus is the one inside the harness jar (feedharness/mejournal-e1/, checked
#     against the jar's e1.pin) unless <e1-dir> names another copy.
# The C++ side never writes these files. Pass "-" for the first two arguments to regenerate only the feed files.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
# the engines' single-file golden printers run on the engine jars and need the agrona opens as flags; the S9h harness
# jar carries Add-Opens in its manifest and is run with plain `java -jar` (review FIX-2), as every consumer runs it
JAVA_OPTS=(--add-opens java.base/jdk.internal.misc=ALL-UNNAMED)

if [ $# -lt 2 ] || [ $# -gt 4 ]; then
    echo "usage: $0 <assets-cluster.jar|-> <match-cluster.jar|-> [<assets-feed-harness.jar> [<e1-dir>]]" >&2
    exit 64
fi

if [ "$1" != "-" ] && [ "$2" != "-" ]; then
    {
        echo "// GENERATED by adapters/sbe/tests/golden/regen.sh from the engines' Java encoders. Do not edit."
        echo "// assets: $(basename "$1")  match: $(basename "$2")"
        java "${JAVA_OPTS[@]}" -cp "$1" "$HERE/GoldenMoney.java"
        java "${JAVA_OPTS[@]}" -cp "$2" "$HERE/GoldenMatch.java"
    } > "$HERE/golden_frames.inc.tmp"
    mv "$HERE/golden_frames.inc.tmp" "$HERE/golden_frames.inc"
    echo "wrote $HERE/golden_frames.inc"
fi

if [ $# -ge 3 ]; then
    HARNESS=$3
    LOCK="$ROOT/dependencies.lock"
    want=$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1])).get("feed_harness_sha256", ""))' "$LOCK")
    got=$(sha256sum "$HARNESS" | cut -d' ' -f1)
    if [ -n "$want" ] && [ "$want" != "$got" ]; then
        echo "FATAL: $HARNESS sha256 $got, dependencies.lock feed_harness_sha256 $want" >&2
        exit 1
    fi
    TMP=$(mktemp -d -t ct-feed-regen.XXXXXX)
    trap 'rm -rf "$TMP"' EXIT
    java -jar "$HARNESS" version > "$TMP/version.txt"
    commit=$(sed -n 's/^assets_commit=//p' "$TMP/version.txt")
    dirty=$(sed -n 's/^assets_worktree_dirty=//p' "$TMP/version.txt")
    java -jar "$HARNESS" fixtures "$ROOT/archive/tests/fixtures/mejournal" "$TMP/fixtures"
    {
        echo "// GENERATED by adapters/sbe/tests/golden/regen.sh from the S9h feed harness. Do not edit (S9a 9.4)."
        echo "// harness: assets $commit (worktree dirty: $dirty)  jar sha256 $got"
        cat "$TMP/fixtures/feed_cases.inc"
    } > "$HERE/feed_frames.inc.tmp"
    mv "$HERE/feed_frames.inc.tmp" "$HERE/feed_frames.inc"
    echo "wrote $HERE/feed_frames.inc"

    E1_SRC=${4:-}
    if [ -z "$E1_SRC" ]; then
        E1_SRC="$TMP/e1-src"
        mkdir -p "$E1_SRC"
        (cd "$E1_SRC" && unzip -q "$HARNESS" 'feedharness/mejournal-e1/*')
        E1_SRC="$E1_SRC/feedharness/mejournal-e1"
    fi
    E1_OUT="$ROOT/domain/bridge/tests/fixtures/e1"
    rm -rf "$E1_OUT.tmp"
    java -jar "$HARNESS" e1 "$E1_SRC" "$E1_OUT.tmp"
    rm -rf "$E1_OUT"
    mv "$E1_OUT.tmp" "$E1_OUT"
    echo "wrote $E1_OUT"
fi
